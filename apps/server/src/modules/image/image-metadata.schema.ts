import { z } from 'zod'

export const ImageMetadataSchema = z.object({
  variants: z.record(z.string(), z.string()).optional(),
  capturedAt: z.string().optional(),
  metadata: z.object({ capturedAt: z.string().optional() }).optional(),
  thumbhash: z.string().optional(),
  timezoneOffset: z.number().optional(),
  latitude: z.number().nullable().optional(),
  longitude: z.number().nullable().optional(),
  width: z.number().nullable().optional(),
  height: z.number().nullable().optional(),
  takenAt: z.union([z.string(), z.date()]).nullable().optional(),
  camera: z.object({
    make: z.string().optional(),
    model: z.string().optional(),
    lens: z.string().optional(),
    serialNumber: z.string().optional(),
  }).optional(),
  settings: z.object({
    iso: z.number().optional(),
    aperture: z.number().optional(),
    apertureValue: z.number().optional(),
    shutterSpeed: z.string().optional(),
    exposureTime: z.number().optional(),
    focalLength: z.number().optional(),
    focalLengthIn35mmFormat: z.number().optional(),
    exposureMode: z.number().optional(),
    whiteBalance: z.number().optional(),
    meteringMode: z.number().optional(),
    flash: z.union([z.boolean(), z.number()]).optional(),
  }).optional(),
  technical: z.object({
    format: z.string().optional(),
    colorSpace: z.string().optional(),
    orientation: z.number().optional(),
    fileSize: z.number().optional(),
    resolutionX: z.number().optional(),
    resolutionY: z.number().optional(),
    resolutionUnit: z.string().optional(),
  }).optional(),
  gps: z.object({
    altitude: z.number().optional(),
    speed: z.number().optional(),
    bearing: z.number().optional(),
    destBearing: z.number().optional(),
    gpsDate: z.string().optional(),
  }).optional(),
  iptc: z.object({
    headline: z.string().optional(),
    caption: z.string().optional(),
    keywords: z.array(z.string()).optional(),
    city: z.string().optional(),
    country: z.string().optional(),
  }).optional(),
  software: z.object({
    modifyDate: z.union([z.string(), z.date()]).optional(),
    software: z.string().optional(),
    creator: z.string().optional(),
    copyright: z.string().optional(),
  }).optional(),
  rawExif: z.record(z.string(), z.unknown()).optional(),
})
